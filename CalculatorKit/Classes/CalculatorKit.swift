import Foundation

public class CalculatorKit {
    
    public init() {
    }
    
    public func add(_ a: Int, _ b: Int) -> Int {
        return a + b
    }

    public func subtract(_ a: Int, _ b: Int) -> Int {
        return a - b
    }
}
